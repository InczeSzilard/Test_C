using System;

namespace Test
{
    // Programmer seniority levels (required for every programmer)
    public enum Seniority
    {
        Junior,
        Mid,
        Senior
    }

    // Abstract base class: cannot be instantiated, only its subclasses can.
    // Holds what every person has: an id and a name.
    public abstract class Person
    {
        // Private field behind the validated Name property (encapsulation)
        private string name;

        // Database id; only this class and its subclasses can change it
        public int Id { get; protected set; }

        // Name of the person; cannot be empty, surrounding spaces are removed
        public string Name
        {
            get { return name; }
            protected set
            {
                if (string.IsNullOrWhiteSpace(value))
                    throw new ArgumentException("A név nem lehet üres.");
                name = value.Trim();
            }
        }

        // Protected constructor: callable only from subclasses
        protected Person(int id, string name)
        {
            Id = id;
            Name = name;   // goes through the validating setter
        }

        // Polymorphism: every subclass overrides this and returns its own role name
        public abstract string GetRoleName();

        // Readable text form, e.g. "Kovács Anna (Junior programmer)"
        public override string ToString()
        {
            return Name + " (" + GetRoleName() + ")";
        }
    }

    // Abstract employee: a person with a monthly salary.
    // Still abstract, because every employee must have a concrete role.
    public abstract class Employee : Person
    {
        // Monthly working hours used for the hourly rate (exam rule: / 160)
        public const decimal MonthlyWorkHours = 160m;

        // Private field behind the validated MonthlySalary property
        private decimal monthlySalary;

        // Monthly gross salary in RON; must be positive
        public decimal MonthlySalary
        {
            get { return monthlySalary; }
            protected set
            {
                if (value <= 0)
                    throw new ArgumentException("A havi bruttó bérnek pozitívnak kell lennie.");
                monthlySalary = value;
            }
        }

        // Passes id and name to Person, then sets the salary
        protected Employee(int id, string name, decimal monthlySalary) : base(id, name)
        {
            MonthlySalary = monthlySalary;
        }

        // HourlyRate = MonthlySalary / 160
        // Virtual: a subclass could override it if it had a different rule
        public virtual decimal GetHourlyRate()
        {
            return MonthlySalary / MonthlyWorkHours;
        }

        // Used only by the database layer after saving (sets the id generated by SQLite)
        internal void SetId(int id)
        {
            Id = id;
        }
    }

    // Programmer: the only employee type that can be a developer on a project
    public class Programmer : Employee
    {
        // Junior, Mid or Senior (required)
        public Seniority Seniority { get; private set; }

        public Programmer(int id, string name, decimal monthlySalary, Seniority seniority)
            : base(id, name, monthlySalary)
        {
            Seniority = seniority;
        }

        // e.g. "Senior programmer"
        public override string GetRoleName()
        {
            return Seniority + " programmer";
        }
    }

    // Project manager: the only employee type that can be a project's PM
    public class ProjectManager : Employee
    {
        public ProjectManager(int id, string name, decimal monthlySalary)
            : base(id, name, monthlySalary) { }

        public override string GetRoleName()
        {
            return "Project manager";
        }
    }

    // Director: listed among employees, but cannot be assigned to a project team
    public class Director : Employee
    {
        public Director(int id, string name, decimal monthlySalary)
            : base(id, name, monthlySalary) { }

        public override string GetRoleName()
        {
            return "Director";
        }
    }

    // HR director: inherits from Director (exam requirement) and overrides the role name again
    public class HrDirector : Director
    {
        public HrDirector(int id, string name, decimal monthlySalary)
            : base(id, name, monthlySalary) { }

        public override string GetRoleName()
        {
            return "HR director";
        }
    }
}